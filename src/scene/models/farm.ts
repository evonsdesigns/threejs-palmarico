import { FarmCrop } from "../../logic/game";
import { buildCropField } from "./crop-field";
import { Kit } from "./kit";

export function buildFarm(kit: Kit, crop: FarmCrop) {
  const { box, gable, frontWindow } = kit;
  buildCropField(kit, crop, [{ x: 2, z: 4 }], () => 0);
  box(0x82755f, -4.5, 0.35, -5.4, 8.5, 0.25, 7.3);
  box(0x737b77, -8.65, 2.55, -5.4, 0.25, 4.4, 7.2);
  box(0x737b77, -0.35, 2.55, -5.4, 0.25, 4.4, 7.2);
  box(0x737b77, -4.5, 2.55, -8.95, 8.4, 4.4, 0.2);
  box(0x737b77, -7.65, 2.55, -1.82, 2.1, 4.4, 0.2);
  box(0x737b77, -1.35, 2.55, -1.82, 2.1, 4.4, 0.2);
  box(0x737b77, -4.5, 4.6, -1.82, 4.3, 0.4, 0.2);
  box(0x5a4938, -4.5, 0.42, -4.3, 4, 0.12, 4.5);
  for (const x of [-6.65, -2.35]) {
    box(0x4d8c46, x, 2.2, -1.68, 0.6, 3.65, 0.14);
    box(0x78966c, x, 2.2, -1.59, 0.05, 3.5, 0.03);
  }
  box(0x52654d, -4.5, 3.55, -1.68, 2.4, 1.1, 0.12);
  frontWindow(-4.5, 3.55, -1.56, 1.8, 0.7);
  for (let x = -8.4; x <= -0.5; x += 0.55) box(0x9b9d92, x, 2.6, -9.07, 0.035, 4.3, 0.04);
  gable(-4.5, -5.4, 8.9, 7.8, 4.8, 2.5, 0xa6573b, 8);
  const roofAngle = Math.atan2(2.5, 3.9);
  for (const [x, z, color] of [[-7.7, -7.9, 0xb47c65], [-4.3, -6.5, 0x858079], [-1.6, -3.2, 0x9a6b55], [-6.4, -3.7, 0xc08167]] as const) {
    const side = z < -5.4 ? -1 : 1;
    const y = 4.8 + 2.5 * (1 - Math.abs(z + 5.4) / 3.9) + 0.12;
    box(color, x, y, z, 1.05, 0.07, 1.1, side * roofAngle);
  }
  box(0x737b77, -9, 1.9, 0.2, 4.1, 3.1, 4);
  frontWindow(-9.7, 2.1, 2.24, 1, 1.1);
  box(0x4f634a, -8.1, 1.55, 2.24, 1.2, 2.4, 0.12);
  gable(-9, 0.2, 4.4, 4.3, 3.5, 0.7, 0xa6573b, 6);
  box(0x887955, 1.8, 0.55, -1, 1.4, 0.85, 1.4);
  box(0x727870, 1.8, 1.05, -1, 1.5, 0.15, 1.5);
  for (const x of [1.15, 2.45]) box(0x72573d, x, 1.65, -1, 0.12, 2.3, 0.12);
  box(0xa6573b, 1.8, 2.85, -1, 1.8, 0.18, 1.25);
  box(0x878a7d, 1.8, 1.22, -1, 0.45, 0.35, 0.45);
}
