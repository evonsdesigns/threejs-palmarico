export function buildTenement(kit: Kit) {
  const { box, window, frontWindow, backWindow, leftWindow } = kit;
  box(0x706f66, 0, 0.25, 0, 21.4, 0.5, 10.2);
  box(0x92908a, 0, 5.85, 0, 21, 11, 9.6);
  for (const x of [-8.4, -4.2, 0, 4.2, 8.4]) {
    box(0x895f50, x, 5.8, 4.82, 2.45, 10.7, 0.08);
    box(0x76584d, x, 5.8, -4.82, 2.45, 10.7, 0.08);
    for (let y = 0.8; y < 11; y += 0.38) {
      box(0xa17e6e, x, y, 4.88, 2.35, 0.035, 0.03);
    }
    for (const y of [1.8, 4.5, 7.2, 9.9]) {
      frontWindow(x - 1.45, y, 4.9, 0.85, 1.35);
      backWindow(x - 1.45, y, -4.9, 0.85, 1.35);
      backWindow(x + 1.1, y, -4.9, 0.85, 1.35);
      box(0x4c5a57, x + 0.25, y - 0.12, 4.91, 0.85, 1.85, 0.08);
      box(0xb7b9aa, x + 0.25, y + 0.13, 4.97, 0.07, 1.3, 0.04);
      box(0xb7b9aa, x + 0.25, y + 0.28, 4.97, 0.85, 0.06, 0.04);
      box(0xa5aaa0, x, y - 1.02, 5.42, 3.2, 0.18, 1.25);
      box(0xbbbcb0, x, y - 0.42, 5.99, 3.15, 0.95, 0.12);
      box(0x858e89, x, y + 0.04, 5.99, 3.18, 0.09, 0.15);
      for (const dx of [-1.57, 1.57]) box(0x959b91, x + dx, y - 0.42, 5.42, 0.1, 0.95, 1.2);
    }
  }
  for (const y of [0.55, 3.2, 5.9, 8.6, 11.25]) {
    box(0x718884, 0, y, 0, 21.15, 0.14, 9.75);
  }
  for (const y of [1.8, 4.5, 7.2, 9.9]) {
    for (const z of [-3.1, -1.05, 1.05, 3.1]) {
      leftWindow(-10.56, y, z, 0.8, 1.3);
      window(10.56, y, z, 0.8, 1.3, Math.PI / 2);
    }
  }
  box(0x343b3c, 0, 11.45, 0, 21.5, 0.35, 10.15);
  for (const z of [-4.3, -2.6, -0.9, 0.8, 2.5, 4.2]) box(0x555c59, 0, 11.64, z, 20.8, 0.035, 0.06);
  for (const x of [-7.8, -2.1, 5.6]) {
    box(0x616d69, x, 11.72, -2.6, 1.5, 0.16, 1.1);
    box(0x414c49, x, 12.35, -2.6, 0.35, 1.3, 0.35);
    box(0x707b75, x, 13.05, -2.6, 0.55, 0.12, 0.55);
  }
  box(0x7d6b55, -1, 12.7, 1, 3.5, 2.1, 2.3);
  box(0x4e5e5b, -1, 12.65, 2.17, 0.9, 1.5, 0.08);
  box(0x858079, -1, 13.85, 1, 3.8, 0.16, 2.65, -0.12);
  for (let x = -2.7; x <= 0.7; x += 0.3) box(0x9a735e, x, 13.96, 1, 0.05, 0.04, 2.65, -0.12);
  for (const x of [1.4, 5.8]) box(0x646960, x, 12.55, 2.8, 0.08, 1.8, 0.08);
  box(0x8c8d7f, 3.6, 13.32, 2.8, 4.4, 0.05, 0.05);
  for (const [x, color, h] of [[2.1, 0xb57857, 0.65], [2.85, 0xd0c2a8, 0.8], [3.7, 0x718b86, 0.6], [4.5, 0xb5967d, 0.75]] as const) {
    box(color, x, 13.27 - h / 2, 2.8, 0.55, h, 0.05);
  }
  for (let floor = 0; floor < 3; floor++) {
    const base = 1.1 + floor * 2.7;
    box(0x404846, 11.45, base, 0, 1.65, 0.12, 6);
    for (const z of [-2.9, 2.9]) {
      box(0x414b48, 12.2, base + 0.6, z, 0.08, 1.2, 0.08);
    }
    box(0x414b48, 12.2, base + 1.15, 0, 0.08, 0.08, 5.8);
    for (let step = 0; step < 9; step++) {
      const z = floor % 2 === 0 ? -2.3 + step * 0.55 : 2.3 - step * 0.55;
      box(0x555d58, 11.45, base + 0.16 + step * 0.3, z, 1.45, 0.09, 0.28);
    }
  }
  for (const [x, y, color] of [[-8.6, 4.2, 0xa97158], [-4.2, 6.9, 0x688d87], [4.3, 9.6, 0xc7a779], [8.4, 4.2, 0x7f9a8b]] as const) {
    box(color, x, y, 6.06, 0.75, 0.7, 0.04);
  }
}
